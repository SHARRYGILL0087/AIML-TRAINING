# Operators
# + - / * **
a = 3
b = 6

print(a + b)
print(a - b)
print(a / b)
print(a * b)
print(a ** 2)

# Comparison Operators
# == != >= <= > <
print(a == b)
print(a != b)
print(a < b)
print(a > b)

a = 3.32
b = 3.32

print(a == b)  # Compare values
print(id(a))
print(id(b))

# Membership Operators
# in, not in
a = "Sharry Gill"

print("h" in a)      # True
print("z" in a)      # False
print("z" not in a)  # True

# Logical 
# and    or   not
a = 3 
b = 2
print(a==3 and b==2)
print(a==3 or b==1)
print(not(a==3 or b==2))
